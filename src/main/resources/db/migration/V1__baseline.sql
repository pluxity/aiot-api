-- Hibernate 7.4 PostgreSQL 방언으로 엔티티에서 생성한 baseline (incident 도입 직전 스키마)
-- 기존 DB는 baseline-on-migrate로 이 버전을 건너뛴다
CREATE EXTENSION IF NOT EXISTS postgis;

create table action_history (
    created_at timestamp(6) not null,
    event_history_id bigint not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    content varchar(255),
    created_by varchar(255),
    updated_by varchar(255),
    primary key (id)
);

create table action_history_file (
    action_history_id bigint not null,
    file_id bigint not null,
    id bigint generated by default as identity,
    primary key (id)
);

create table announcement (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    site_id bigint not null,
    updated_at timestamp(6) not null,
    message varchar(1000),
    created_by varchar(255),
    updated_by varchar(255),
    primary key (id)
);

create table cctv (
    camera_analysis_configured integer,
    camera_port integer,
    camera_record_type integer,
    latitude float(53),
    longitude float(53),
    ptz_control integer,
    stream_resolution_height integer,
    stream_resolution_width integer,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    site_id bigint,
    updated_at timestamp(6) not null,
    camera_address varchar(255),
    camera_ip varchar(255),
    camera_status varchar(255) check ((camera_status in ('DISCONNECTED','NORMAL','FAULT'))),
    camera_type varchar(255) check ((camera_type in ('IP','VIDEO','PTZ','AIBOX','AI','UNMANAGED','UNSUPPORTED'))),
    created_by varchar(255),
    eds_camera_id varchar(255) not null unique,
    name varchar(255),
    updated_by varchar(255),
    geom geometry(Point, 4326),
    primary key (id)
);

create table eds_event (
    event_id integer not null,
    event_zone_id integer,
    latitude float(53),
    longitude float(53),
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    index bigint not null unique,
    thumbnail_file_id bigint,
    updated_at timestamp(6) not null,
    camera_id varchar(255),
    created_by varchar(255),
    detected_vehicle_number varchar(255),
    event_end varchar(255),
    event_start varchar(255),
    event_status varchar(255) check ((event_status in ('STARTED','IN_PROGRESS','ENDED'))),
    event_type varchar(255) check ((event_type in ('LOITERING','PATH_PASS','DIRECTIONAL_MOVE','ENTER','EXIT','STOP','ABANDONED','LINE_CROSS','SMOKE','FLAME','FALL_DOWN','CROWD','VIOLENCE','MULTI_LINE_CROSS','VEHICLE_ACCIDENT','VEHICLE_STOP','TRAFFIC_JAM','COLOR_CHANGE','VEHICLE_PARKING','REMOVED','DANGER_WATER_LEVEL','AREA_COLOR','STAY','STAY_OVERCROWDED','STAY_TIMEOUT','STAY_ALONE','NO_HELMET','LEFT_ALONE','APPROACH','SEPARATE','ACTION_RECOGNITION','VEHICLE_TAILGATING','JAYWALKING','FARE_EVASION','NO_MASK','NO_SAFETY_VEST','PEDESTRIAN_DANGER','PEDESTRIAN_STATISTICS','FLASHLIGHT','LICENSE_PLATE_RECOGNITION','GAUGE_RECOGNITION','CAKE_RECOGNITION','SAFETY_HOOK_UNLATCHED','NO_KORAIL_UNIFORM','CROWD_DENSITY','FACE_RECOGNITION','VEHICLE_PLATE','WEAPON_THREAT'))),
    event_zone_name varchar(255),
    frame_time varchar(255),
    profile_name varchar(255),
    updated_by varchar(255),
    primary key (id)
);

create table event_history (
    latitude float(53),
    longitude float(53),
    max_value float(53),
    min_value float(53),
    value float(53) not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    occurred_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    created_by varchar(255),
    device_id varchar(255) not null,
    event_name varchar(255) not null,
    field_key varchar(255) not null,
    guide_message varchar(255),
    level varchar(255) check ((level in ('NORMAL','WARNING','CAUTION','DANGER','DISCONNECTED'))),
    object_id varchar(255) not null,
    sensor_description varchar(255) not null,
    status varchar(255) check ((status in ('ACTIVE','IN_PROGRESS','RESOLVED'))),
    unit varchar(255) not null,
    updated_by varchar(255),
    primary key (id)
);

create table event_condition (
    boolean_value boolean,
    is_active boolean,
    left_value float(53),
    notification_enabled boolean not null,
    right_value float(53),
    threshold_value float(53),
    id bigint generated by default as identity,
    condition_type varchar(255) check ((condition_type in ('SINGLE','RANGE'))),
    field_key varchar(255) not null,
    guide_message varchar(255),
    level varchar(255) not null check ((level in ('NORMAL','WARNING','CAUTION','DANGER','DISCONNECTED'))),
    object_id varchar(255) not null,
    operator varchar(255) check ((operator in ('GE','LE','BETWEEN'))),
    primary key (id)
);

create table feature (
    battery_level integer,
    height float(53),
    is_active boolean not null,
    latitude float(53),
    longitude float(53),
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    site_id bigint,
    subscription_time timestamp(6),
    updated_at timestamp(6) not null,
    event_status varchar(50),
    created_by varchar(255),
    device_id varchar(255) not null unique,
    name varchar(255),
    object_id varchar(255) not null,
    updated_by varchar(255),
    geom geometry(Point, 4326),
    primary key (id)
);

create table files (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    content_type varchar(255) not null,
    created_by varchar(255),
    file_path varchar(255) not null unique,
    file_status varchar(255) not null check ((file_status in ('TEMP','COMPLETE'))),
    original_file_name varchar(255) not null,
    updated_by varchar(255),
    primary key (id)
);

create table llm_message (
    today_avg_temp float(53) not null,
    yesterday_avg_temp float(53) not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    site_id bigint not null,
    updated_at timestamp(6) not null,
    prompt varchar(500) not null,
    message varchar(1000) not null,
    created_by varchar(255),
    updated_by varchar(255),
    primary key (id)
);

create table mic (
    latitude float(53),
    longitude float(53),
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    site_id bigint,
    updated_at timestamp(6) not null,
    created_by varchar(255),
    edge_id varchar(255),
    host varchar(255),
    name varchar(255),
    status varchar(255) check ((status in ('ACTIVE','INACTIVE','DISCONNECTED'))),
    updated_by varchar(255),
    vendor_mic_id varchar(255) not null unique,
    geom geometry(Point, 4326),
    thresholds jsonb,
    primary key (id)
);

create table mic_event (
    avg_noise float(53),
    confidence float(53),
    latitude float(53),
    longitude float(53),
    max_noise float(53),
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
