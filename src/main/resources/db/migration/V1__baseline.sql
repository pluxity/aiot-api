create table permission (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    permission_group_id bigint,
    updated_at timestamp(6) not null,
    created_by varchar(255),
    resource_id varchar(255) not null,
    resource_name varchar(255) not null,
    updated_by varchar(255),
    primary key (id)
);

create table permission_group (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    created_by varchar(255),
    description varchar(255),
    name varchar(255),
    updated_by varchar(255),
    primary key (id)
);

create table role_permission (
    id bigint generated by default as identity,
    permission_group_id bigint,
    role_id bigint,
    primary key (id)
);

create table roles (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    description varchar(100),
    auth varchar(255),
    created_by varchar(255),
    name varchar(255) not null unique,
    updated_by varchar(255),
    primary key (id)
);

create table site (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    thumbnail_id bigint,
    updated_at timestamp(6) not null,
    name varchar(50) not null,
    created_by varchar(255),
    description varchar(255),
    updated_by varchar(255),
    location geometry(Polygon, 4326),
    primary key (id)
);

create table site_sensor_manager (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    site_id bigint not null,
    updated_at timestamp(6) not null,
    user_id bigint not null,
    sensor_type varchar(50) not null check ((sensor_type in ('TEMPERATURE_HUMIDITY','FIRE','WASTE_FILL_LEVEL','FOREST_FIRE','ODOR_MONITOR','PEOPLE_COUNTER','COMPOSITE_AIR_QUALITY'))),
    created_by varchar(255),
    updated_by varchar(255),
    primary key (id),
    unique (site_id, sensor_type, user_id)
);

create table sms_history (
    result_code integer,
    stat_code integer,
    status_code integer,
    clidx bigint,
    completed_at timestamp(6),
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    result_checked_at timestamp(6),
    updated_at timestamp(6) not null,
    sender_number varchar(40),
    target_number varchar(40) not null,
    failure_reason varchar(1000),
    message varchar(2000) not null,
    created_by varchar(255),
    error_code varchar(255),
    message_type varchar(255),
    result varchar(255) check ((result in ('SUCCESS','FAILURE'))),
    stat varchar(255) not null check ((stat in ('SUCCESS','NO_ACCOUNT','NUMBER_TOO_LONG','NOT_SENT'))),
    status varchar(255) check ((status in ('COMPLETED','CANCELED','ERROR'))),
    title varchar(255) not null,
    updated_by varchar(255),
    primary key (id)
);

create table user_role (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    role_id bigint not null,
    updated_at timestamp(6) not null,
    user_id bigint not null,
    created_by varchar(255),
    updated_by varchar(255),
    primary key (id)
);

create table users (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    last_password_change_date timestamp(6),
    updated_at timestamp(6) not null,
    code varchar(20),
    name varchar(20) not null,
    created_by varchar(255),
    department varchar(255),
    password varchar(255) not null,
    phone_number varchar(255),
    updated_by varchar(255),
    username varchar(255) not null unique,
    primary key (id)
);

